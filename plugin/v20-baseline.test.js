// Baseline characterization of the suite on stock Super Productivity v20.
//
// Each test runs one action through the modular bridge and the packaged
// plugin.js against the same synthetic fixture (test/fixtures/upstream/v20)
// and pins what the suite does today. A test marked "baseline gap" records
// behavior that differs from upstream v20; the roadmap issue named in it
// changes the behavior and updates the assertion. These are not failing
// tests: they pass on the current suite.
//
// True archive (#15) is delivered by the Go server over Local REST
// (internal/bridge), so the plugin cases below only cover the no-REST path.
process.env.TZ = "America/Chicago";

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const fixtureDir = path.join(__dirname, "..", "test", "fixtures", "upstream", "v20");
const { buildAll, serialize } = require(path.join(fixtureDir, "build.js"));
const { createPluginApi, loadFixture, runBoth, writes } = require(path.join(fixtureDir, "harness.js"));

const tasksFixture = loadFixture("tasks.json");

function assertSameOutcome(both) {
  assert.equal(both.modular.ok, both.packaged.ok, "modular and packaged disagree on success");
  if (!both.modular.ok) assert.equal(both.modular.error.code, both.packaged.error.code);
}

test("fixtures are generated by build.js and unchanged", () => {
  for (const [name, value] of Object.entries(buildAll())) {
    assert.equal(fs.readFileSync(path.join(fixtureDir, name), "utf8"), serialize(value), `${name} drifted; run node test/fixtures/upstream/v20/build.js`);
  }
});

test("fixtures contain only synthetic data", () => {
  const text = fs.readdirSync(fixtureDir)
    .filter((name) => name.endsWith(".json"))
    .map((name) => fs.readFileSync(path.join(fixtureDir, name), "utf8"))
    .join("\n");
  assert.doesNotMatch(text, /[\w.+-]+@[\w-]+\.[\w.]+/, "no email addresses");
  assert.doesNotMatch(text, /\b(?:Bearer\s+\w|token\s*[:=]|password|secret)/i, "no credentials");
  for (const task of [...tasksFixture.active, ...tasksFixture.archived]) {
    assert.match(task.title, /^Fixture /, `task ${task.id} has a synthetic title`);
  }
});

